"""Add ATP/IIT to the authoritative calibrated 2x2 factorial.

Scheduling decisions are generated by the unchanged V8 event kernels.  This
script reconstructs the continuous RC trajectory from each cell's dispatch and
completion trace and verifies mandatory DMR against the frozen V8 table before
accepting the thermal metrics.  It does not infer thermal values from the old
hard-coded comprehensive figure.
"""

from __future__ import annotations

import csv
import json
import math
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from experiments.initial_manuscript_event_replay import temperature_excursion_integral
from experiments.initial_manuscript_hbtasp import TAMB, VOLTAGES, end_temperature
from experiments import run_v5_final_factorial as factorial

ROOT = Path(__file__).resolve().parents[1]
POOL_PATH = ROOT / "experiments/checkpoints/v8_calibrated_final_factorial/calibrated_histogram_test_pool.json"
AUTH_PATH = ROOT / "experiments/checkpoints/v8_calibrated_final_factorial/cell_results.csv"
OUT = ROOT / "experiments/checkpoints/v9_thermal_augmented_factorial"
RESULT = OUT / "cell_results.csv"
CONFIGS = factorial.CONFIGS
PERIODS = factorial.PERIODS
LINES = factorial.LINES
SEEDS = factorial.SEEDS
BETA = 0.5058

_POOL = None
_AUTH = None


def steady_state(voltage: float) -> float:
    return 0.1 * (41.01 + 512.635 * voltage**3) / BETA


def temperature_integral(start: float, voltage: float, duration: float) -> float:
    if duration <= 0:
        return 0.0
    tss = steady_state(voltage)
    return tss * duration - (tss - start) * (1.0 - math.exp(-BETA * duration)) / BETA


def segment_peak(start: float, voltage: float, duration: float) -> float:
    end = end_temperature(start, voltage, duration)
    return max(start, end)


def reconstruct_thermal(trace: list[dict]) -> dict[str, float]:
    states = [
        {"temp": float(TAMB), "time": 0.0, "integral": 0.0, "iit": 0.0,
         "peak": float(TAMB), "active": None}
        for _ in range(2)
    ]
    horizon = max((float(e["time"]) for e in trace if "time" in e), default=0.0)

    for event in trace:
        kind = event.get("event")
        if kind not in ("dispatch", "complete") or "processor" not in event:
            continue
        processor = int(event["processor"])
        state = states[processor]
        now = float(event["time"])

        if kind == "dispatch":
            if state["active"] is not None:
                raise RuntimeError("overlapping dispatch on one processor")
            idle = now - state["time"]
            if idle < -1e-12:
                raise RuntimeError("non-monotone processor trace")
            if idle > 0:
                state["integral"] += temperature_integral(state["temp"], VOLTAGES[0], idle)
                state["iit"] += temperature_excursion_integral(state["temp"], VOLTAGES[0], idle)
                state["peak"] = max(state["peak"], segment_peak(state["temp"], VOLTAGES[0], idle))
                state["temp"] = end_temperature(state["temp"], VOLTAGES[0], idle)
                state["time"] = now
            recorded = float(event["temperature"])
            if abs(recorded - state["temp"]) > 2e-8:
                raise RuntimeError(f"dispatch-temperature mismatch: {recorded} vs {state['temp']}")
            state["active"] = {
                "uid": event["uid"], "start": now, "temperature": recorded,
                "voltage": float(event["voltage"]),
            }

        else:
            active = state["active"]
            if active is None or active["uid"] != event["uid"]:
                raise RuntimeError("completion without matching dispatch")
            duration = now - active["start"]
            voltage = active["voltage"]
            start = active["temperature"]
            state["integral"] += temperature_integral(start, voltage, duration)
            state["iit"] += temperature_excursion_integral(start, voltage, duration)
            state["peak"] = max(state["peak"], segment_peak(start, voltage, duration))
            predicted = end_temperature(start, voltage, duration)
            recorded = float(event["temperature"])
            if abs(predicted - recorded) > 2e-8:
                raise RuntimeError(f"completion-temperature mismatch: {recorded} vs {predicted}")
            state["temp"] = recorded
            state["time"] = now
            state["active"] = None

    for state in states:
        if state["active"] is not None:
            raise RuntimeError("unfinished active segment")
        idle = horizon - state["time"]
        if idle > 0:
            state["integral"] += temperature_integral(state["temp"], VOLTAGES[0], idle)
            state["iit"] += temperature_excursion_integral(state["temp"], VOLTAGES[0], idle)
            state["peak"] = max(state["peak"], segment_peak(state["temp"], VOLTAGES[0], idle))

    denominator = len(states) * horizon
    return {
        "average_temperature_c": sum(s["integral"] for s in states) / denominator,
        "iit_celsius_seconds": sum(s["iit"] for s in states),
        "peak_temperature_c": max(s["peak"] for s in states),
        "observation_horizon_s": horizon,
    }


def init_worker() -> None:
    global _POOL, _AUTH
    _POOL = json.loads(POOL_PATH.read_text(encoding="utf-8"))
    auth = pd.read_csv(AUTH_PATH)
    _AUTH = {
        (r.configuration, int(r.period_ms), int(r.lines), int(r.seed)): r._asdict()
        for r in auth.itertuples(index=False)
    }


def run_key(key: tuple[str, int, int, int]) -> dict:
    config, period, lines, seed = key
    summary, trace, mandatory = factorial.run_cell(config, _POOL, period, lines, seed)
    auth = _AUTH[key]
    if abs(float(mandatory["mandatory_dmr"]) - float(auth["mandatory_dmr"])) > 1e-12:
        raise RuntimeError(f"mandatory DMR mismatch for {key}")
    thermal = reconstruct_thermal(trace)
    return {
        "configuration": config, "period_ms": period, "lines": lines, "seed": seed,
        "mandatory_dmr": float(auth["mandatory_dmr"]),
        "mean_complete_image_dice": float(auth["mean_complete_image_dice"]),
        "pixel_defect_recall": float(auth["pixel_defect_recall"]),
        "image_complete_miss_rate": float(auth["image_complete_miss_rate"]),
        "thermal_violations": int(summary["thermal_violations"]),
        **thermal,
    }


def write_rows(rows: list[dict]) -> None:
    tmp = RESULT.with_suffix(".tmp")
    with tmp.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    tmp.replace(RESULT)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    keys = [(c, p, l, s) for c in CONFIGS for p in PERIODS for l in LINES for s in SEEDS]
    rows: list[dict] = []
    if RESULT.exists():
        rows = pd.read_csv(RESULT).to_dict("records")
    done = {(r["configuration"], int(r["period_ms"]), int(r["lines"]), int(r["seed"])) for r in rows}
    pending = [k for k in keys if k not in done]
    started = time.time()
    with ProcessPoolExecutor(max_workers=4, initializer=init_worker) as executor:
        futures = {executor.submit(run_key, key): key for key in pending}
        for future in as_completed(futures):
            rows.append(future.result())
            rows.sort(key=lambda r: (CONFIGS.index(r["configuration"]), int(r["period_ms"]),
                                     int(r["lines"]), int(r["seed"])))
            write_rows(rows)
            checkpoint = {
                "status": "complete" if len(rows) == len(keys) else "running",
                "completed_cells": len(rows), "total_cells": len(keys),
                "updated_utc": datetime.now(timezone.utc).isoformat(),
                "elapsed_seconds_this_run": time.time() - started,
                "protocol": {"configs": CONFIGS, "periods_ms": PERIODS,
                             "lines": LINES, "seeds": SEEDS, "epochs": factorial.EPOCHS,
                             "thermal_reconstruction": "continuous RC from unchanged event traces"},
            }
            (OUT / "checkpoint.json").write_text(json.dumps(checkpoint, indent=2), encoding="utf-8")
            if len(rows) % 20 == 0 or len(rows) == len(keys):
                print(f"[{len(rows)}/{len(keys)}]", flush=True)


if __name__ == "__main__":
    main()
